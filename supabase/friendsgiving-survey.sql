-- Friendsgiving reflections are anonymous, but the responses are not public.
-- Server-only secrets in request headers authorize writes and spreadsheet exports.

create schema if not exists private;

create table if not exists private.friendsgiving_survey_secrets (
  name text primary key,
  secret_hash text not null,
  updated_at timestamptz not null default now()
);

revoke all on schema private from public;
revoke all on table private.friendsgiving_survey_secrets from public, anon, authenticated;
grant usage on schema private to anon;

create or replace function private.validate_friendsgiving_secret(p_name text, p_secret text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select p_secret is not null
    and exists (
      select 1
      from private.friendsgiving_survey_secrets
      where name = p_name
        and secret_hash = md5(p_secret)
    );
$$;

revoke all on function private.validate_friendsgiving_secret(text, text) from public, anon, authenticated;

create or replace function private.friendsgiving_request_secret_valid(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.validate_friendsgiving_secret(
    p_name,
    coalesce(current_setting('request.headers', true), '{}')::jsonb ->> 'x-friendsgiving-secret'
  );
$$;

revoke all on function private.friendsgiving_request_secret_valid(text) from public, anon, authenticated;
grant execute on function private.friendsgiving_request_secret_valid(text) to anon;

create table if not exists public.friendsgiving_survey_responses (
  id bigint generated by default as identity primary key,
  submission_id uuid not null unique,
  submitted_at timestamptz not null default now(),
  praise text not null check (char_length(praise) between 1 and 1000),
  different text not null check (char_length(different) between 1 and 1000),
  learned text not null check (char_length(learned) between 1 and 1000)
);

comment on table public.friendsgiving_survey_responses is
  'Anonymous Friendsgiving reflections. Access is restricted to server-held request secrets.';

alter table public.friendsgiving_survey_responses enable row level security;

revoke all on table public.friendsgiving_survey_responses from public, anon, authenticated;
grant insert, select on table public.friendsgiving_survey_responses to anon;

drop policy if exists "Server can submit Friendsgiving reflections" on public.friendsgiving_survey_responses;
create policy "Server can submit Friendsgiving reflections"
on public.friendsgiving_survey_responses
for insert
to anon
with check (
  (select private.friendsgiving_request_secret_valid('write'))
);

drop policy if exists "Spreadsheet can export Friendsgiving reflections" on public.friendsgiving_survey_responses;
create policy "Spreadsheet can export Friendsgiving reflections"
on public.friendsgiving_survey_responses
for select
to anon
using (
  (select private.friendsgiving_request_secret_valid('export'))
);
